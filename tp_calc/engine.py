# -*- coding: utf-8 -*-
"""
Порт ядра расчёта цен из общего модуля тп_РасчетЦен (конфигурация «Транспортные перевозки»).
Перенесён базовый путь «по старому»: приоритетный подбор базовой цены + вес/объём +
экспресс-цена + допрасходы за доставку. Продвинутые ветки (бренд/Z/авиа и «по новому»:
тарифы на перевозку, растаможка, наценки) оформлены как точки расширения в extensions.py.

Источник логики: 02_ИзвлечённыеИсходники/ОбщийМодуль_тп_РасчетЦен.bsl
"""
from __future__ import annotations
from dataclasses import dataclass, field
from datetime import date
from typing import Optional
from . import extensions


@dataclass
class CalcInput:
    """Аналог структуры ДанныеДляРасчета (входные параметры калькуляции)."""
    общий_вес: float                 # кг
    общий_объем: float               # м3
    вид_товара: str                  # идентификатор/код вида товара
    группа_вида_товара: Optional[str] = None   # родитель вида товара (для приоритета 2/3)
    тип_упаковки: Optional[str] = None
    склад: Optional[str] = None
    клиент: Optional[str] = None
    вид_операции: str = "ОднородныйТовар"   # ОднородныйТовар | Экспресс | ПриемПочты | ПриемПочтыСтационарный
    экспресс_доставка: bool = False
    дата: date = field(default_factory=date.today)
    брэнд: bool = False
    z_товар: bool = False
    не_начислять_допрасход: bool = False
    # Поля для ветки «по новому»
    вид_тарифа_на_перевозку: Optional[str] = None  # определяется по виду операции (справочник тп_ВидыТарифовНаПеревозку)
    количество_мест: int = 0                        # для растаможки «по количеству»
    количество_в_упаковке: int = 0


@dataclass
class CalcResult:
    цена_за_тонну: float = 0.0
    цена_за_куб: float = 0.0
    сумма: float = 0.0                       # стоимость перевозки (без допрасходов)
    сумма_допрасходов_за_доставку: float = 0.0
    сумма_бренд: float = 0.0
    сумма_z: float = 0.0
    сумма_за_перевозку: float = 0.0          # ветка «по новому» (расширение)
    сумма_за_растаможку: float = 0.0         # ветка «по новому» (расширение)
    итого: float = 0.0
    средний_вес: float = 0.0
    по_весу: bool = False
    цена_по_основному_регистру: bool = False
    источник_цены: Optional[str] = None      # какой регистр/приоритет дал цену
    примечания: list = field(default_factory=list)


def рассчитать(inp: CalcInput, prices: "PriceRepository", *, расчет_по_новому: bool = False) -> CalcResult:
    """
    Главная точка входа. Аналог тп_РасчетЦен.РасчетСреднейЦены(..., ЭтоКалькуляция=Истина).
    """
    res = CalcResult()

    # Аналог: при ВидОперации = ПриемПочты расчёт не выполняется
    if inp.вид_операции == "ПриемПочты":
        return res

    res.средний_вес = round(inp.общий_вес / inp.общий_объем, 2) if inp.общий_объем else 0.0

    if расчет_по_новому:
        # Ветка «по новому»: перевозка + растаможка + наценки — точки расширения.
        extensions.рассчитать_по_новому(inp, res, prices)
    else:
        _рассчитать_по_старому(inp, res, prices)

    _рассчитать_допрасходы(inp, res, prices)

    res.итого = round(res.сумма + res.сумма_допрасходов_за_доставку, 2)
    return res


def _рассчитать_по_старому(inp: CalcInput, res: CalcResult, prices: "PriceRepository") -> None:
    """
    Аналог РасчетСреднейЦеныПоСтарому: приоритетный подбор базовой цены (источники 0..5),
    затем расчёт по весу или по объёму, с учётом экспресс-цены.
    """
    настройки = prices.настройки_расчета(inp.дата)   # РасчетЭкспресс/Авиа/Бренд/Z
    строка = prices.подобрать_базовую_цену(inp, res.средний_вес)   # первая по приоритету/периоду
    if строка is None:
        res.примечания.append("Базовая цена не найдена по регистрам ЦеныНаГруз* — сумма = 0.")
        return

    только_свои = prices.склад_только_свои_цены(inp.склад)
    if только_свои and not строка.склад:
        res.примечания.append("Склад принимает только собственные цены, а подобрана цена без склада — не применяется.")
        return

    res.источник_цены = строка.источник

    if строка.по_весу:
        # Цена задана за тонну
        if inp.экспресс_доставка and настройки.расчет_экспресс:
            res.цена_за_тонну = строка.экспресс_цена
        else:
            res.цена_за_тонну = строка.цена
        res.сумма = inp.общий_вес / 1000.0 * res.цена_за_тонну
        res.цена_за_куб = (res.сумма / inp.общий_объем) if inp.общий_объем else 0.0
        res.по_весу = True
    else:
        # Цена задана за куб
        if inp.экспресс_доставка and настройки.расчет_экспресс:
            res.цена_за_куб = строка.экспресс_цена
        else:
            res.цена_за_куб = строка.цена
        res.сумма = inp.общий_объем * res.цена_за_куб
        res.цена_за_тонну = (res.сумма / inp.общий_вес * 1000.0) if inp.общий_вес else 0.0
        res.по_весу = False

    # Наценки за бренд / Z-товар — расширение (зависит от отдельных регистров/настроек)
    if inp.брэнд and настройки.расчет_бренд:
        res.сумма_бренд = extensions.сумма_за_бренд(inp, строка, prices)
        res.сумма += res.сумма_бренд
    if inp.z_товар and настройки.расчет_z:
        res.сумма_z = extensions.сумма_za_z(inp, строка, prices)
        res.сумма += res.сумма_z

    res.цена_по_основному_регистру = True
    res.сумма = round(res.сумма, 2)
    res.цена_за_тонну = round(res.цена_за_тонну, 2)
    res.цена_за_куб = round(res.цена_за_куб, 2)


def _рассчитать_допрасходы(inp: CalcInput, res: CalcResult, prices: "PriceRepository") -> None:
    """
    Аналог РасчетДопРасходовЗаДоставку: коэффициент дорожных расходов * вес,
    либо расчёт по таблице ЦенаДопРасходов (по весу/объёму).
    """
    if inp.вид_операции == "ПриемПочтыСтационарный" or inp.не_начислять_допрасход:
        res.сумма_допрасходов_за_доставку = 0.0
        return

    if not (inp.общий_объем > 0 and inp.общий_вес > 0):
        res.сумма_допрасходов_за_доставку = 0.0
        return

    коэф = prices.коэффициент_дорожных_расходов(inp.склад, inp.дата)  # (.коэффициент, .расчет_по_таблице)
    if коэф is None:
        res.сумма_допрасходов_за_доставку = 0.0
        return

    if коэф.расчет_по_таблице:
        строка_доп = prices.доп_расход_по_весу(inp, res.средний_вес)  # ЦенаДопРасходов
        if строка_доп is None:
            res.сумма_допрасходов_за_доставку = 0.0
            return
        if строка_доп.по_весу:
            res.сумма_допрасходов_за_доставку = round(inp.общий_вес * строка_доп.цена / 1000.0, 2)
        else:
            res.сумма_допрасходов_за_доставку = round(inp.общий_объем * строка_доп.цена, 2)
    else:
        res.сумма_допрасходов_за_доставку = round(inp.общий_вес * коэф.коэффициент, 2)
