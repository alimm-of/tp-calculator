# ---------- Ветка «по новому» (перенос из тп_РасчетЦен_Служебная) ----------

def рассчитать_по_новому(inp, res, prices) -> None:
    растаможка = prices.цена_растаможки(inp)
    тариф = prices.тариф_перевозки(inp, res.средний_вес)
    наценки = prices.наценки_на_товар(inp.дата)

    if растаможка is None:
        res.примечания.append(
            "Ветка «по новому»: не найдена цена растаможки (тп_ЦеныНаРастаможку)."
        )
        return
    # Тариф нужен только если логистика НЕ включена (иначе перевозку не считаем)
    if not растаможка["логистика_включена"] and тариф is None:
        res.примечания.append(
            "Ветка «по новому»: не найден тариф на перевозку (тп_ТарифыНаПеревозку)."
        )
        return

    # Растаможка
    if растаможка["по_весу"]:
        сумма_растаможки = inp.общий_вес / 1000.0 * растаможка["цена"]
    elif растаможка["по_количеству"]:
        количество = (inp.количество_мест or 0) * (inp.количество_в_упаковке or 0)
        сумма_растаможки = количество * растаможка["цена"]
    else:
        сумма_растаможки = inp.общий_объем * растаможка["цена"]

    # Перевозка
    if растаможка["логистика_включена"]:
        сумма_перевозки = 0.0
    else:
        if тариф["по_весу"]:
            сумма_перевозки = inp.общий_вес / 1000.0 * тариф["цена"]
            res.по_весу = True
        else:
            сумма_перевозки = inp.общий_объем * тариф["цена"]
            res.по_весу = False

    # Наценки
    настройки = prices.настройки_расчета(inp.дата)
    сумма_наценок = 0.0
    это_авиа = (inp.вид_операции == "ПриемПочтыСтационарный")

    сумма_бренд = 0.0
    if inp.брэнд and настройки.расчет_бренд and ("Бренд" in наценки):
        сумма_бренд = (inp.общий_вес if это_авиа else inp.общий_объем) * наценки["Бренд"]
        сумма_наценок += сумма_бренд
    res.сумма_бренд = round(сумма_бренд, 2)

    сумма_z = 0.0
    if inp.z_товар and настройки.расчет_z and ("Батарея" in наценки):
        сумма_z = inp.общий_объем * наценки["Батарея"]
        сумма_наценок += сумма_z
    res.сумма_z = round(сумма_z, 2)

    # Итоги
    res.сумма_за_перевозку = round(сумма_перевозки, 2)
    res.сумма_за_растаможку = round(сумма_растаможки, 2)
    res.сумма = round(сумма_перевозки + сумма_растаможки + сумма_наценок, 2)
    if inp.общий_вес:
        res.цена_за_тонну = round(res.сумма / inp.общий_вес * 1000.0, 2)
    if inp.общий_объем:
        res.цена_за_куб = round(res.сумма / inp.общий_объем, 2)
    res.цена_по_основному_регистру = True


